export function isLocalWeatherQuestion(text) {
  const s = text.trim().replace(/[，,、\s]/g, '').replace(/[？?。！!]+$/g, '').replace(/^(露米|Lumi)/, '小日');
  return /^(?:小日)?(?:請)?(?:幫我|告訴我|我想知道)?(?:查一下|看看|查查)?(?:今天|現在|目前|這裡|這邊|外面|等等|待會|等一下)?的?(?:天氣(?:如何|怎麼樣|怎樣|好不好)?|(?:會不會|會|有沒有|有|在)下雨|下雨了|要不要帶傘|要帶傘|需要帶傘|氣溫(?:多少|幾度)?|幾度|熱不熱|冷不冷)(?:嗎|呢|啊|呀)?$/.test(s);
}
